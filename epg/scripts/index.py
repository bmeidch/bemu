#!/usr/bin/env python3
"""Merge XMLTV feeds listed as alternating filenames and URLs."""

from __future__ import annotations

import argparse
import tempfile
from pathlib import Path
from urllib.parse import urlparse

import requests
from lxml import etree


def read_feed_list(source: Path) -> list[tuple[str, str]]:
    """Read the project's alternating filename/URL feed-list format."""
    lines = [line.strip() for line in source.read_text(encoding="utf-8").splitlines()]
    lines = [line for line in lines if line and not line.startswith("#")]
    if len(lines) % 2:
        raise ValueError(f"{source}: expected filename/URL pairs; found an unmatched line")

    feeds = []
    for filename, url in zip(lines[0::2], lines[1::2]):
        parsed = urlparse(url)
        if Path(filename).name != filename or not filename.lower().endswith(".xml"):
            raise ValueError(f"Invalid feed filename: {filename!r}")
        if parsed.scheme not in {"http", "https"} or not parsed.netloc:
            raise ValueError(f"Invalid feed URL for {filename}: {url!r}")
        feeds.append((filename, url))
    return feeds


def parse_xml(path: Path) -> etree._Element:
    parser = etree.XMLParser(resolve_entities=False, no_network=True, recover=False)
    return etree.parse(str(path), parser).getroot()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("result", type=Path, help="output XML file")
    parser.add_argument("source", type=Path, help="alternating feed filename/URL list")
    parser.add_argument("caption_name")
    parser.add_argument("caption_url")
    args = parser.parse_args()

    if not args.source.is_file():
        parser.error(f"source list does not exist: {args.source}")

    feeds = read_feed_list(args.source)
    args.result.parent.mkdir(parents=True, exist_ok=True)
    mapping_dir = args.source.parent

    with tempfile.TemporaryDirectory(prefix="epg-") as temporary_dir:
        temporary_path = Path(temporary_dir)
        session = requests.Session()
        session.headers.update({"User-Agent": "bemu-epg-generator/1.0"})

        roots: list[tuple[str, etree._Element]] = []
        for filename, url in feeds:
            local_path = temporary_path / filename
            print(f"Downloading {filename}...", flush=True)
            response = session.get(url, timeout=(15, 120))
            response.raise_for_status()
            local_path.write_bytes(response.content)
            roots.append((filename, parse_xml(local_path)))

        tree = etree.Element(
            "tv",
            {
                "generator-info-name": f"EPG generated by {args.caption_name}",
                "generator-info-url": args.caption_url,
            },
        )

        for tag_name, attribute in (("channel", "id"), ("programme", "channel")):
            print(f"Merging {tag_name}...", flush=True)
            for filename, root in roots:
                mapping_path = mapping_dir / f"{filename}.txt"
                replacements = {}
                if mapping_path.is_file():
                    for line in mapping_path.read_text(encoding="utf-8").splitlines():
                        line = line.strip()
                        if line and not line.startswith("#"):
                            parts = line.split(",", maxsplit=1)
                            if len(parts) != 2 or not all(part.strip() for part in parts):
                                raise ValueError(f"Invalid mapping in {mapping_path}: {line!r}")
                            replacements[parts[0].strip()] = parts[1].strip()

                for child in root:
                    if etree.QName(child).localname != tag_name:
                        continue
                    value = child.get(attribute)
                    if value is None:
                        raise ValueError(f"{filename}: <{tag_name}> is missing {attribute!r}")
                    if value in replacements:
                        child.set(attribute, replacements[value])
                    tree.append(child)

        output = etree.tostring(tree, encoding="UTF-8", xml_declaration=True, pretty_print=True)
        # Replace the destination only after every feed was downloaded and parsed successfully.
        with tempfile.NamedTemporaryFile(dir=args.result.parent, delete=False) as temporary_file:
            temporary_file.write(output)
            temporary_output = Path(temporary_file.name)
        temporary_output.replace(args.result)
        session.close()
        print(f"Created {args.result}", flush=True)


if __name__ == "__main__":
    main()
